async def main():
    user = await oms.authorize_access()
    file = open("out.txt", "w+")
    tasks = [user.fetch_itn_info(itn) for itn in ITNS.split()]
    total = len(tasks)
    
    for data in tqdm(as_completed(tasks), total = total):
        try:
            result = await data
        except ClientResponseError as err:
            file.write(f"{err.message} - Error. Retry later\n")
            raise err

        itn = result["data"]["inventory"]["InventoryTrackingNumber"]
        try:
            location = result['data']['inventory']['BinLocation']
        except TypeError:
            file.write(f"{itn} - Dead ITN\n")
            continue
        file.write(f"{itn} - {location}\n")   

    await user.close_session()
    file.close()

if __name__ == "__main__":
    asyncio.run(main())